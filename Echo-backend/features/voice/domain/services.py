from typing import Protocol

from features.voice.domain.entities import StreamingRecognitionUpdate, SynthesizedVoiceAudio


class VoiceAudioStorage(Protocol):
    def save_upload(self, audio_bytes: bytes, suffix: str = ".mp3") -> str: ...

    def delete_upload(self, audio_path: str) -> None: ...

    async def save_generated_audio(self, audio_bytes: bytes, suffix: str = ".mp3") -> str: ...


class VoiceRecognizer(Protocol):
    async def recognize(self, audio_path: str) -> str: ...


class VoiceSynthesizer(Protocol):
    async def synthesize(self, text: str) -> SynthesizedVoiceAudio: ...


class VoiceStreamingRecognitionSession(Protocol):
    async def send_audio(self, audio_bytes: bytes) -> None: ...

    async def finish(self) -> None: ...

    async def receive_update(self) -> StreamingRecognitionUpdate: ...

    async def close(self) -> None: ...


class VoiceStreamingRecognizer(Protocol):
    async def open_session(self) -> VoiceStreamingRecognitionSession: ...
